import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import fs from "fs";
import path from "path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const vaultPluginDir = "/Users/gavinbender/Code/FA26-notes/.obsidian/plugins/obsidian-notesheet";

function syncToVault() {
  if (fs.existsSync(vaultPluginDir)) {
    if (fs.existsSync("main.js")) {
      fs.copyFileSync("main.js", path.join(vaultPluginDir, "main.js"));
    }
    if (fs.existsSync("styles.css")) {
      fs.copyFileSync("styles.css", path.join(vaultPluginDir, "styles.css"));
    }
    if (fs.existsSync("manifest.json")) {
      fs.copyFileSync("manifest.json", path.join(vaultPluginDir, "manifest.json"));
    }
    console.log("Synced build artifacts to " + vaultPluginDir);
  }
}

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  plugins: [
    {
      name: "copy-to-vault",
      setup(build) {
        build.onEnd(() => {
          if (fs.existsSync("src/styles.css")) {
            fs.copyFileSync("src/styles.css", "styles.css");
          }
          syncToVault();
        });
      },
    },
  ],
});

// Copy styles.css if present
if (fs.existsSync("src/styles.css")) {
  fs.copyFileSync("src/styles.css", "styles.css");
}

if (prod) {
  await context.rebuild();
  if (fs.existsSync("src/styles.css")) {
    fs.copyFileSync("src/styles.css", "styles.css");
  }
  syncToVault();
  process.exit(0);
} else {
  await context.watch();
}
